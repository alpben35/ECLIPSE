import { readFileSync } from 'node:fs';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { doc, setDoc, updateDoc, getDoc, deleteDoc, serverTimestamp } from 'firebase/firestore';
import { ref, uploadBytes, getBytes } from 'firebase/storage';
import assert from 'node:assert/strict';
const env = await initializeTestEnvironment({ projectId:'demo-eclipse', firestore:{host:'127.0.0.1',port:8088,rules:readFileSync('firestore.rules','utf8')}, storage:{host:'127.0.0.1',port:9198,rules:readFileSync('storage.rules','utf8')} });
try {
 const alice = env.authenticatedContext('alice',{email:'alice@example.test',email_verified:true});
 const bob = env.authenticatedContext('bob',{email:'bob@example.test',email_verified:true});
 const guest = env.unauthenticatedContext();
 const aliceDb=alice.firestore(), bobDb=bob.firestore(), guestDb=guest.firestore();
 const aliceStorage=alice.storage(), bobStorage=bob.storage();
 await assertSucceeds(setDoc(doc(aliceDb,'users/alice'),{uid:'alice',email:'alice@example.test',rank:'Student',tier:'free'}));
 await assertFails(updateDoc(doc(aliceDb,'users/alice'),{rank:'Admin'}));
 await assertFails(updateDoc(doc(aliceDb,'users/alice'),{tier:'premium'}));
 await assertFails(setDoc(doc(bobDb,'users/bob'),{uid:'bob',rank:'Owner',tier:'admin'}));
 await assertFails(getDoc(doc(bobDb,'users/alice')));
 await assertFails(getDoc(doc(guestDb,'users/alice')));
 await assertSucceeds(updateDoc(doc(aliceDb,'users/alice'),{theme:'dark'}));
 await assertSucceeds(setDoc(doc(aliceDb,'users/alice/messages/message'),{role:'user',content:'Explain fractions',timestamp:serverTimestamp()}));
 await assertSucceeds(deleteDoc(doc(aliceDb,'users/alice/messages/message')));
 await assertFails(setDoc(doc(aliceDb,'public_profiles/alice'),{uid:'alice',email:'private@example.test'}));
 await assertSucceeds(setDoc(doc(aliceDb,'public_profiles/alice'),{uid:'alice',displayName:'Learner',rank:'Student'}));
 await assertSucceeds(setDoc(doc(aliceDb,'groups/private-group'),{name:'Private study',createdBy:'alice',members:['alice'],isPrivate:true}));
 await assertFails(getDoc(doc(bobDb,'groups/private-group')));
 await assertFails(updateDoc(doc(bobDb,'groups/private-group'),{members:['alice','bob']}));
 const storage=aliceStorage;
 await assertSucceeds(uploadBytes(ref(storage,'users/alice/sample.png'),new Uint8Array([1,2,3]),{contentType:'image/png'}));
 await assertFails(uploadBytes(ref(bobStorage,'users/alice/overwrite.png'),new Uint8Array([1]),{contentType:'image/png'}));
 await assertFails(getBytes(ref(bobStorage,'users/alice/sample.png')));
 await assertFails(uploadBytes(ref(storage,'users/alice/script.html'),new Uint8Array([1]),{contentType:'text/html'}));
 await assertFails(uploadBytes(ref(storage,'users/alice/large.png'),new Uint8Array(10*1024*1024+1),{contentType:'image/png'}));
 const seed=await fetch('http://127.0.0.1:8088/v1/projects/demo-eclipse/databases/ai-studio-2a66ed90-2fcf-4fc3-abef-a32720185065/documents/groups/member-group', {method:'PATCH',headers:{Authorization:'Bearer owner','Content-Type':'application/json'},body:JSON.stringify({fields:{members:{arrayValue:{values:[{stringValue:'alice'}]}}}})});
 assert.equal(seed.ok,true);
 await assertSucceeds(uploadBytes(ref(aliceStorage,'groups/member-group/images/test.png'),new Uint8Array([1]),{contentType:'image/png'}));
 await assertFails(getBytes(ref(bobStorage,'groups/member-group/images/test.png')));
 await assertFails(setDoc(doc(aliceDb,'agent_tasks/fake-approval'),{status:'approved_waiting_executor'}));
 await assertFails(getDoc(doc(aliceDb,'agent_messages/private-discussion')));
 console.log('PASS: 23 security checks, including private workshop access and named-database group file membership.');
} finally { await env.cleanup(); }
